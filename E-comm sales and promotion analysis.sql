-- Q8. Which promoted products had the highest user activity on their promotion dates?

select distinct event_date, ProductId, COUNT(event_type) as user_activity_count from events
inner join promotion
on product_id = ProductId
and event_date = eventdate
group by productId, event_date, productid
order by user_activity_count desc
limit 1;

